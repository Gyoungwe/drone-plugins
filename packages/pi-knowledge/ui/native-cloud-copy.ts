export function useNativeKnowledgeCloudText() {
	return useLanguage() === "zh" ? zh : en;
}

export function cloudReason(t: typeof zh, reason: string): string {
	return Object.hasOwn(t.reasons, reason) ? t.reasons[reason as keyof typeof t.reasons] : t.genericError;
}
