import { createHash } from "node:crypto";
import { execFileSync } from "node:child_process";
import { existsSync, mkdirSync, readFileSync, readdirSync, writeFileSync } from "node:fs";
import { join, relative, resolve } from "node:path";
import { build } from "esbuild";
import postcss from "postcss";

const root = resolve(import.meta.dirname, "..");
const check = process.argv.includes("--check");
const pkg = JSON.parse(readFileSync(join(root, "package.json"), "utf8"));
const manifest = JSON.parse(readFileSync(join(root, "plugin.manifest.json"), "utf8"));
const ui = JSON.parse(readFileSync(join(root, "ui/plugin.json"), "utf8"));
if (pkg.version !== manifest.version || pkg.version !== ui.version) throw new Error("Package and manifests must share one version");
if (manifest.drone.pluginApi !== 1 || ui.droneUi !== 1 || ui.main !== "bundle.js") throw new Error("Unsupported UI contract");

function walk(dir) {
	return readdirSync(dir, { withFileTypes: true }).flatMap((e) => e.isDirectory() ? walk(join(dir,e.name)) : [join(dir,e.name)]);
}
const sources = walk(join(root, "ui")).filter((p) => /\.(tsx?|css)$/.test(p) && !/\.test\./.test(p) && !p.endsWith("styles/generated.ts"));
for (const path of sources) {
	const text = readFileSync(path,"utf8");
	if (/from ["']@drone\//.test(text) || /window\.pi\b/.test(text) || /from ["']electron["']/.test(text)) throw new Error(`Host-private dependency: ${relative(root,path)}`);
}
const rawUtilities = execFileSync(process.execPath, [resolve(root,"../../node_modules/@tailwindcss/cli/dist/index.mjs"), "-i", join(root,"ui/styles/utilities.css"), "--minify"], {encoding:"utf8", maxBuffer: 4 * 1024 * 1024});
// Tailwind property registrations and cascade layers are document-global,
// even when every selector is prefixed. Keep both namespaces plugin-owned.
const scoped = postcss.parse(rawUtilities.replaceAll("--tw-", "--drone-task-tw-"));
scoped.walkAtRules("layer", layer => {
 layer.params = layer.params.split(",").map(name => `drone-task-${name.trim()}`).join(",");
});
scoped.walkRules(rule => {
	if (rule.parent?.type === "atrule" && rule.parent.name.endsWith("keyframes")) return;
	rule.selectors = rule.selectors.map(selector => selector === ":root" || selector === ":host" ? ":where(.drone-task-ui)" : `:where(.drone-task-ui) ${selector}`);
});
const css = scoped.toString()+"\n"+readFileSync(join(root,"ui/styles/task.css"),"utf8");
const generated = `// Generated by scripts/build-ui.mjs; edit styles sources instead.\nexport const taskStyles = ${JSON.stringify(css)};\n`;
const virtualStyles = { name:"knowledge-styles", setup(b) {
	b.onResolve({filter:/\/styles\/generated$/}, args=>({path:args.path, namespace:"generated-style"}));
	b.onLoad({filter:/.*/,namespace:"generated-style"},()=>({contents:generated,loader:"ts"}));
}};
const bundled = await build({entryPoints:[join(root,"ui/entry.tsx")], bundle:true,write:false,format:"esm",platform:"browser",target:"chrome140",jsx:"automatic",external:["react","react-dom","react/jsx-runtime"],plugins:[virtualStyles],logLevel:"silent"});
const outputs = new Map([
	["ui/styles/generated.ts",generated],
	["ui/bundle.js",bundled.outputFiles[0].text],
]);
const sha = value=>createHash("sha256").update(value).digest("hex");
const inputs = Object.fromEntries([...sources,join(root,"scripts/build-ui.mjs"),join(root,"package.json"),join(root,"plugin.manifest.json"),join(root,"ui/plugin.json")].sort().map(path=>[relative(root,path),sha(readFileSync(path))]));
outputs.set("ui/build-manifest.json", JSON.stringify({artifactSource:"ui/entry.tsx",inputs,outputs:Object.fromEntries([...outputs].map(([path,text])=>[path,sha(text)]))},null,2)+"\n");
for(const [path,text] of outputs) {
	const target=join(root,path);
	if(check){if(!existsSync(target)||readFileSync(target,"utf8")!==text)throw new Error(`Stale generated output: ${path}`);}
	else {mkdirSync(resolve(target,".."),{recursive:true});writeFileSync(target,text);}
}
console.log(`[pi-core UI] ${check ? "checked" : "built"} ${ui.name}@${pkg.version}`);
